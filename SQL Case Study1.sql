-- 15. Display the table with the following attributes such as date, 
-- productID, product_type, product, sales, profit, state, area_code. 
select f.Date, f.ProductId, p.Product_Type, p.product, 
f.Sales, f.Profit, l.state, f.area_code from 
fact as f join product as p 
on f.ProductId = p.ProductId 
join location as l on f.area_code = l.area_code 

-- 16. Display the rank without any gap to show the sales wise rank. 
select *, dense_RANK() over(order by sales) as sales_rank from fact

-- 17. Find the state wise profit and sales. 
select l.State, sum(Profit) as total_profit, sum(Sales) as total_sale from fact as f 
join location as l on f.area_code = l.Area_Code
group by state

-- 18. Find the state wise profit and sales along with the productname. 
select l.State, p.Product, sum(profit) as total_profit, sum(sales) as total_sales
from fact as f join location as l 
on f.Area_Code = l.Area_Code 
join product as p 
on p.ProductId = f.ProductId
group by l.State, p.Product

-- 19. If there is an increase in sales of 5%, calculate the increased sales. 
